"""Light maps for the WebGL pass, one PNG per panel image, same framing as the crop.
R = craquelure (thin dark cracks), G = ink mask, B = relief (local shading, 0.5 = flat)."""
import sys, json, base64, io
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
Image.MAX_IMAGE_PIXELS = None

def box_for(orig, tat, h, aspect):
    a = np.asarray(Image.open(orig).convert("L"), np.int16); b = np.asarray(Image.open(tat).convert("L"), np.int16)
    ys, xs = np.nonzero(np.abs(a - b) > 12); cx, cy = np.median(xs), np.median(ys)
    H = 9 * h; W = H * aspect
    top = min(max(cy - 0.55 * H, 0), a.shape[0] - H); left = min(max(cx - W / 2, 0), a.shape[1] - W)
    return (int(left), int(top), int(left + W), int(top + H))

def maps(orig, tat, box, size):
    o = Image.open(orig).convert("RGB").crop(box).resize(size, Image.LANCZOS)
    t = Image.open(tat).convert("RGB").crop(box).resize(size, Image.LANCZOS)
    Lo = np.asarray(o.convert("L"), np.float32) / 255
    Lt = np.asarray(t.convert("L"), np.float32) / 255
    crack = ndi.grey_closing(Lo, size=(5, 5)) - Lo                # black top-hat: thin dark lines
    crack = np.clip(crack / (np.percentile(crack, 99.3) + 1e-6), 0, 1) ** 1.2
    ink = np.clip((Lo - Lt) / 0.12, 0, 1); ink = ndi.gaussian_filter(ink, 0.8)
    rel = ndi.gaussian_filter(Lo, 1.2) - ndi.gaussian_filter(Lo, 10)  # brushwork and canvas relief
    rel = np.clip(0.5 + rel / (4 * rel.std() + 1e-6), 0, 1)
    rgb = np.dstack([crack, ink, rel])
    return Image.fromarray((rgb * 255).astype(np.uint8)), t

def uri(im, fmt, **kw):
    b = io.BytesIO(); im.save(b, fmt, **kw); return f"data:image/{fmt.lower()};base64," + base64.b64encode(b.getvalue()).decode()

OUT = sys.argv[1]
panels = {
  "open": ("odalisque.jpg", "odalisque-tat.jpg", (0, 820, 4480, 3620), (2400, 1500)),
  "milkmaid": ("milkmaid.jpg", "milkmaid-tat.jpg", ("box", 133, 0.8), (960, 1200)),
  "bride": ("bride.jpg", "bride-tat.jpg", ("box", 96, 0.8), (960, 1200)),
  "socrates": ("socrates.jpg", "socrates-tat.jpg", ("box", 56, 1.5), (1800, 1200)),
  "musicians": ("musicians.jpg", "musicians-tat.jpg", ("box", 230, 1.5), (1800, 1200)),
  "adam": ("adam.jpg", "adam-tat-thuglife.jpg", ("box", 200, 0.8), (960, 1200)),
  "pearl": ("pearl.jpg", "pearl-face-tat.jpg", ("box", 105, 0.8), (960, 1200)),
}
js = ["// generated by aux.py: colour and light maps as data URIs, so WebGL can read them under file://", "const GL = {};"]
for k, (o, t, bx, size) in panels.items():
    box = box_for(o, t, bx[1], bx[2]) if bx[0] == "box" else bx
    aux, col = maps(o, t, box, size)
    js.append(f"GL.{k} = {{ col: '{uri(col, 'JPEG', quality=88)}', aux: '{uri(aux, 'JPEG', quality=86, subsampling=0)}' }};")
    print(k, box, size)
open(f"{OUT}/gl-data.js", "w").write("\n".join(js) + "\n")
